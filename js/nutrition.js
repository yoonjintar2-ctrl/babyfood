  const REF = { kcal: 600, protein: 15, iron: 6 };

  function day(menus) {
    const t = { kcal: 0, carb: 0, protein: 0, fat: 0, iron: 0 }, missing = new Set();
    let n = 0;
    for (const m of menus) {
      const serves = Math.max(1, Number(m.serves) || 1);
      for (const g of m.ings || []) {
        const v = of(g.name, Number(g.qty) || 0, g.unit);
        if (!v) { if (g.name) missing.add(g.name); continue; }
        for (const k in t) t[k] += v[k] / serves;
        n++;
      }
    }
    return { ...t, counted: n, missing: [...missing] };
  }

